# Ввод чисел от 0 до 100

percent = int(input("Введите заполненность группы (от 0 до 100): "))

# Проверка диапазона

if percent < 0 or percent > 100:
    print("Ошибка диапазона")
else:
    # Определяем категорию для 8 варианта
    if 0 <= percent <= 39:
        print("Есть места")
    elif 40 <= percent <= 79:
        print("Группа набирается")
    else:
        print("Почти заполнена")